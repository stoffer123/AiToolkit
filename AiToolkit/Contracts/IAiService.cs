using System;
using System.Collections.Generic;
using System.Text;

namespace AiToolkit.Contracts
{
    /// <summary>
    /// Sends requests to a large language model provider and returns the generated text.
    /// </summary>
    /// <remarks>
    /// Implementations translate the provider-neutral <see cref="AiRequest"/> into the
    /// provider's own API format, and are responsible for validating provider-specific
    /// constraints such as which models support sampling or reasoning parameters.
    /// </remarks>
    public interface IAiService
    {
        /// <summary>
        /// The models this service supports, including which parameters each one accepts.
        /// </summary>
        IReadOnlyList<ModelInfo> SupportedModels { get; }

        /// <summary>
        /// Sends the request to the model and returns the generated text.
        /// </summary>
        /// <param name="request">The request to send. Build one with <c>PromptBuilder</c>.</param>
        /// <param name="ct">Token used to cancel the request.</param>
        /// <returns>The text output generated by the model.</returns>
        /// <exception cref="ArgumentException">The model is unknown to this provider.</exception>
        /// <exception cref="NotSupportedException">
        /// The request uses a parameter the selected model does not support.
        /// </exception>
        /// <exception cref="InvalidOperationException">
        /// The response was incomplete, for example because the output token limit was reached.
        /// </exception>
        Task<string> GetResponseAsync(AiRequest request, CancellationToken ct = default);
    }
}
